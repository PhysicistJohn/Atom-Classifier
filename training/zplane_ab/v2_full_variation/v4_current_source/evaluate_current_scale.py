@dataclass(frozen=True)
class ScaleGeneratorLineageBinding:
    """Exact reviewed generator source and bundle accepted by one caller."""

    source_sha256: str
    bundle_sha256: str


DEFAULT_SCALE_GENERATOR_LINEAGE = ScaleGeneratorLineageBinding(
    source_sha256=EXPECTED_SCALE_GENERATOR_SOURCE_SHA256,
    bundle_sha256=EXPECTED_SCALE_GENERATOR_BUNDLE_SHA256,
)


def _fixed_public_class(profile: str) -> str:
    """Independently map the current fixed-profile catalog to public labels."""
    if profile.startswith("gsm-"):
        return "gsm"
    if profile == "wifi-hr-dsss-11m":
        return "dsss"
    if profile.startswith("bluetooth-"):
        return "bluetooth"
    if (
        profile.startswith("lte-")
        or profile.startswith("nr-")
        or profile == "wifi-ofdm-20m"
        or profile.startswith("wifi6-")
    ):
        return "ofdm"
    raise ValueError(f"unknown fixed SignalLab profile {profile!r}")


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _sha256_bytes(value: bytes | memoryview) -> str:
    return hashlib.sha256(value).hexdigest()


def _generator_lineage_binding(
    expected: ScaleGeneratorLineageBinding = DEFAULT_SCALE_GENERATOR_LINEAGE,
) -> str:
    if not isinstance(expected, ScaleGeneratorLineageBinding):
        raise TypeError(
            "expected scale generator lineage must be an exact binding object"
        )
    source_sha256 = _hash_string(
        expected.source_sha256,
        "expected scale generator source SHA-256",
    )
    bundle_sha256 = _hash_string(
        expected.bundle_sha256,
        "expected scale generator bundle SHA-256",
    )
    return hashlib.sha256(
        "\0".join(
            (
                GENERATOR_LINEAGE_SCHEMA,
                SCALE_GENERATOR_PATH,
                source_sha256,
                SCALE_GENERATOR_BUNDLE_PATH,
                bundle_sha256,
            )
        ).encode("utf-8")
    ).hexdigest()


def _validate_generator_lineage(
    manifest: Mapping[str, Any],
    expected: ScaleGeneratorLineageBinding = DEFAULT_SCALE_GENERATOR_LINEAGE,
) -> None:
    if not isinstance(expected, ScaleGeneratorLineageBinding):
        raise TypeError(
            "expected scale generator lineage must be an exact binding object"
        )
    source_sha256 = _hash_string(
        expected.source_sha256,
        "expected scale generator source SHA-256",
    )
    bundle_sha256 = _hash_string(
        expected.bundle_sha256,
        "expected scale generator bundle SHA-256",
    )
    if manifest.get("generatorPath") != SCALE_GENERATOR_PATH:
        raise ValueError("scale-eval generatorPath drifted")
    lineage = manifest.get("generatorLineage")
    if not isinstance(lineage, Mapping):
        raise ValueError("scale-eval generatorLineage must be an object")
    expected = {
        "schema": GENERATOR_LINEAGE_SCHEMA,
        "repository": "Atom-Classifier",
        "sourcePath": SCALE_GENERATOR_PATH,
        "sourceSha256": source_sha256,
        "bundlePath": SCALE_GENERATOR_BUNDLE_PATH,
        "bundleSha256": bundle_sha256,
        "sourceBundleBindingSha256": _generator_lineage_binding(expected),
    }
    for field, value in expected.items():
        if lineage.get(field) != value:
            raise ValueError(
                f"scale-eval generatorLineage.{field} drifted"
            )


def _jsonable(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    if isinstance(value, np.ndarray):
        return _jsonable(value.tolist())
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        value = float(value)
    if isinstance(value, float):
        return value if np.isfinite(value) else None
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, torch.device):
        return str(value)
    return value


def _write_json_exclusive(path: Path, payload: Any) -> None:
    if path.exists():
        raise FileExistsError(f"refusing to overwrite evaluation: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    try:
        with temporary.open("x", encoding="utf-8") as handle:
            json.dump(
                _jsonable(payload),
                handle,
                indent=2,
                sort_keys=True,
                allow_nan=False,
            )
            handle.write("\n")
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def reject_sensitive_path(path: str | Path, role: str) -> Path:
    """Resolve and reject release, sealed, or consumed-test locations."""
    resolved = Path(path).expanduser().resolve()
    components = [part.lower().replace("_", "-") for part in resolved.parts]
    if (
        any("release" in part for part in components)
        or any("sealed" in part for part in components)
        or any(
            "consumed-test" in part or "consumedtest" in part
            for part in components
        )
    ):
        raise ValueError(
            "current service scale evaluation refuses release, sealed, or "
            f"consumed-test {role} paths: {resolved}"
        )
    return resolved


def _read_json(path: Path, role: str) -> dict[str, Any]:
    if not path.is_file():
        raise FileNotFoundError(f"{role} is missing: {path}")
    with path.open(encoding="utf-8") as handle:
        value = json.load(handle)
    if not isinstance(value, dict):
        raise ValueError(f"{role} must be a JSON object")
    return value


def _plain_artifact(
    directory: Path,
    filename: Any,
    field: str,
) -> Path:
    if (
        not isinstance(filename, str)
        or not filename
        or Path(filename).name != filename
    ):
        raise ValueError(f"{field} must be a plain artifact filename")
    path = (directory / filename).resolve()
    if path.parent != directory or not path.is_file():
        raise ValueError(f"{field} artifact is missing: {path}")
    return path


def _positive_integer(value: Any, field: str) -> int:
    if (
        isinstance(value, (bool, np.bool_))
        or not isinstance(value, (int, np.integer))
        or int(value) <= 0
    ):
        raise ValueError(f"{field} must be a positive integer")
    return int(value)


def _integer(value: Any, field: str) -> int:
    if (
        isinstance(value, (bool, np.bool_))
        or not isinstance(value, (int, np.integer))
    ):
        raise ValueError(f"{field} must be an integer")
    return int(value)


def _nonnegative_integer(value: Any, field: str) -> int:
    if (
        isinstance(value, (bool, np.bool_))
        or not isinstance(value, (int, np.integer))
        or int(value) < 0
    ):
        raise ValueError(f"{field} must be a non-negative integer")
    return int(value)


def _finite_float(value: Any, field: str) -> float:
    if isinstance(value, (bool, np.bool_)):
        raise ValueError(f"{field} must be finite")
    try:
        result = float(value)
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError(f"{field} must be finite") from exc
    if not np.isfinite(result):
        raise ValueError(f"{field} must be finite")
    return result


def _nonempty_string(value: Any, field: str) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{field} must be a non-empty string")
    return value


def _hash_string(value: Any, field: str, length: int = 64) -> str:
    if (
        not isinstance(value, str)
        or len(value) != length
        or any(character not in HASH_PATTERN for character in value)
    ):
        raise ValueError(f"{field} must be a lowercase {length * 4}-bit hash")
    return value


