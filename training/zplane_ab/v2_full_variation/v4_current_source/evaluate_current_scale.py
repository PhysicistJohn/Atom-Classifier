@dataclass
class ScaleEvalCorpus:
    directory: Path
    manifest_path: Path
    raw_path: Path
    manifest: dict[str, Any]
    raw: np.memmap
    rows: list[ScaleEvalRow]
    audit: dict[str, Any]

    def prefix(self, row: ScaleEvalRow, length: int) -> np.ndarray:
        if length not in row.available_lengths:
            raise ValueError(
                f"row {row.index} does not admit prefix {length}"
            )
        pair = np.asarray(self.raw[row.index, :length], dtype=np.float64)
        if pair.shape != (length, 2) or not np.isfinite(pair).all():
            raise ValueError(f"row {row.index} prefix {length} is invalid")
        return pair[:, 0] + 1j * pair[:, 1]


